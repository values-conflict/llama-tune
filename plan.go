// fitResult is the verdict of one `llama fit-params` call for a kv type.
type fitResult struct {
	KVType    string
	Requested int
	Fitted    int // -c from the printed args; equals Requested when it fits
	Fits      bool
	NGl       string
	OT        string // override-tensor argument content, "" if none
}

// runFitParams asks llama.cpp to fit ctx on the local hardware with the
// given kv cache type and returns what it settled on.
func runFitParams(llamaBin, modelRef string, modelLocal bool, kv string, ctx, marginMiB int) (fitResult, error) {
	var args []string
	if modelLocal {
		args = append(args, "fit-params", "-m", modelRef)
	} else {
		args = append(args, "fit-params", "-hf", modelRef)
	}
	args = append(args,
		"-c", strconv.Itoa(ctx),
		"-ctk", kv, "-ctv", kv,
		"--fit-target", strconv.Itoa(marginMiB),
	)
	out, err := exec.Command(llamaBin, args...).CombinedOutput()
	if err != nil {
		return fitResult{}, fmt.Errorf("fit-params: %w\n%s", err, string(out))
	}
	fr := fitResult{KVType: kv, Requested: ctx}
	// the printed argument line looks like: -c 262144 -ngl 9999 -ot "a=CPU,b=GPU"
	for _, line := range strings.Split(string(out), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "-c ") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 4 {
			continue
		}
		fr.Fitted, _ = strconv.Atoi(fields[1])
		fr.NGl = fields[3]
		for i, f := range fields {
			if f == "-ot" && i+1 < len(fields) {
				fr.OT = strings.Trim(strings.Join(fields[i+1:], " "), "\"")
			}
		}
		fr.Fits = fr.Fitted >= ctx
		break
	}
	if fr.Fitted == 0 {
		return fitResult{}, fmt.Errorf("fit-params printed no args:\n%s", string(out))
	}
	return fr, nil
}

// cpuCores returns logical and physical CPU counts.
func cpuCores() (logical, physical int) {
	logical = runtime.NumCPU()
	physical = logical
	data, err := os.ReadFile("/sys/devices/system/cpu/cpu0/topology/thread_siblings_list")
	if err == nil {
		for range strings.Split(strings.TrimSpace(string(data)), ",") {
			physical++
		}
		if physical < 1 {
			physical = logical
		}
	}
	return
}

func ladder(max int, step int) []int {
	var out []int
	for d := step; d <= max; d *= 2 {
		out = append(out, d)
	}
	return out
}

func joinInts(v []int) string {
	s := make([]string, len(v))
	for i, n := range v {
		s[i] = strconv.Itoa(n)
	}
	return strings.Join(s, ", ")
}

// cmdPlan emits a sweep config derived from the model and the local
// hardware. The user reviews and tweaks it before running.
func cmdPlan(args []string) error {
	fs := flag.NewFlagSet("plan", flag.ExitOnError)
	model := fs.String("hf", "", "hf ref or local gguf path (required)")
	llamaBin := fs.String("llama-bin", "llama", "path to the unified llama binary")
	ctx := fs.Int("ctx", 0, "target context size (default: the model's trained ctx)")
	margin := fs.Int("margin", 1024, "memory margin for fit-params, MiB")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *model == "" {
		return fmt.Errorf("-hf is required")
	}
	local := !isHFRef(*model)
	modelPath, err := resolveModel(*llamaBin, *model)
	if err != nil {
		return err
	}
	m, err := scanGGUF(modelPath)
	if err != nil {
		return err
	}
	target := *ctx
	if target <= 0 {
		target = int(m.NContext)
	}
	if target <= 0 {
		return fmt.Errorf("no context size: pass -ctx")
	}
	logical, physical := cpuCores()

	// probe each kv type: does target ctx fit, and how does fit place it
	type probe struct {
		kv string
		fr fitResult
		ok bool
	}
	var probes []probe
	for _, kv := range []string{"q4_0", "q8_0", "f16"} {
		fmt.Fprintf(os.Stderr, "fit-params: probing kv %s at ctx %d ...\n", kv, target)
		fr, err := runFitParams(*llamaBin, *model, local, kv, target, *margin)
		if err != nil {
			fmt.Fprintf(os.Stderr, "  skipped: %v\n", err)
			continue
		}
		probes = append(probes, probe{kv, fr, true})
		fmt.Fprintf(os.Stderr, "  -> fits=%v (fitted ctx %d, ngl %s)\n", fr.Fits, fr.Fitted, fr.NGl)
	}
	if len(probes) == 0 {
		return fmt.Errorf("no kv type could be probed")
	}

	// primary = first kv type (smallest first) that fits the target ctx;
	// otherwise the one that fits the most context
	primary := probes[0]
	for _, p := range probes {
		if p.fr.Fits {
			primary = p
			break
		}
	}
	if !primary.fr.Fits && primary.fr.Fitted < target {
		fmt.Printf("note: %d does not fit with any kv type; using %s at %d\n", target, primary.fr.KVType, primary.fr.Fitted)
	}
	ctxSize := primary.fr.Fitted

	var b strings.Builder
	c := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	c("# generated by llama-tune plan on %s", hostname())
	c("# model: %s", *model)
	c("# trained ctx %d, %d layers, gqa %d kv heads, mtp %v, moe %v",
		m.NContext, m.BlockCount, m.NKVHeads, m.MTP, m.NExperts > 0)
	for _, p := range probes {
		c("# fit kv=%s: fits %d ctx: %v (fitted %d)", p.fr.KVType, target, p.fr.Fits, p.fr.Fitted)
	}
	c("#")
	c("# review and tweak before running; sampling defaults are left to you")
	c("")
	if local {
		c("model = %s", *model)
	} else {
		c("hf = %s", *model)
	}
	c("ctx-size = %d", ctxSize)
	c("jinja = true")
	c("parallel = 1")
	c("cache-ram = 3072")
	c("kv-unified = true")
	c("cache-type-k = %s", primary.fr.KVType)
	c("cache-type-v = %s", primary.fr.KVType)
	c("")
	c("[tier1]")
	c("pp = 4096")
	c("gen = 64")
	c("repeats = 2")
	c("depths = %s", joinInts(ladder(min(ctxSize, 65536), 1024)))
	c("")
	c("[tier2]")
	c("gen = 64")
	c("repeats = 1")
	c("warmup = true")
	c("depths = %s", joinInts(ladder(ctxSize, 4096)))
	c("")

	c("[baseline]")
	if primary.fr.OT != "" {
		c("n-gpu-layers = %s", primary.fr.NGl)
		c("override-tensor = %s", primary.fr.OT)
	} else {
		c("n-gpu-layers = all")
	}
	c("threads = %d", physical)
	c("flash-attn = true")
	c("batch-size = 4096")
	c("ubatch-size = 1024")
	if m.MTP {
		c("spec-type = draft-mtp")
		c("spec-draft-n-max = 2")
	} else {
		c("spec-type = ngram-mod")
		c("spec-ngram-mod-n-min = 48")
		c("spec-ngram-mod-n-max = 64")
		c("spec-ngram-mod-n-match = 24")
	}
	c("")
	c("[baseline-nospec]")
	c("inherit = baseline")
	c("spec-type = none")
	c("")

	if m.MTP {
		c("[spec1]")
		c("inherit = baseline")
		c("spec-draft-n-max = 1")
		c("tier1 = no")
		c("")
		c("[spec3]")
		c("inherit = baseline")
		c("spec-draft-n-max = 3")
		c("tier1 = no")
		c("")
	}
	c("[spec-ngram]")
	c("inherit = baseline-nospec")
	c("spec-type = ngram-mod")
	c("spec-ngram-mod-n-min = 48")
	c("spec-ngram-mod-n-max = 64")
	c("spec-ngram-mod-n-match = 24")
	c("tier1 = no")
	c("")

	for _, p := range probes {
		if p.fr.KVType == primary.fr.KVType {
			continue
		}
		c("# kv cache variant: %s (fits ctx %d)", p.kv, p.fr.Fitted)
		c("[kv-" + p.fr.KVType + "]")
		c("inherit = baseline-nospec")
		c("cache-type-k = %s", p.kv)
		c("cache-type-v = %s", p.kv)
		c("ctx-size = %d", p.fr.Fitted)
		if !p.fr.Fits {
			c("depths = %s", joinInts(ladder(p.fr.Fitted, 4096)))
		}
		c("spec-type = none")
		c("")
	}

	if logical != physical {
		c("[threads-logical]")
		c("inherit = baseline-nospec")
		c("threads = %d", logical)
		c("spec-type = none")
		c("depths = %s", joinInts(ladder(min(ctxSize, 65536), 4096)))
		c("")
	}

	if m.NExperts > 0 {
		c("# moe: keep experts of half the layers on cpu")
		c("[ncmoe-half]")
		c("inherit = baseline-nospec")
		c("n-cpu-moe = %d", m.BlockCount/2)
		c("spec-type = none")
		c("depths = %s", joinInts(ladder(min(ctxSize, 65536), 4096)))
		c("")
	}

	c("# escape hatch: move heavy tensors around by hand, e.g.")
	c("# [ot-host-io]")
	c("# inherit = baseline-nospec")
	c("# override-tensor = output=CPU,token_embd=CPU")
	c("# spec-type = none")

	fmt.Fprint(os.Stdout, b.String())
	return nil
}

func hostname() string {
	h, _ := os.Hostname()
	return h
}
